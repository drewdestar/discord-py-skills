#!/usr/bin/env node
// sync-skills.mjs — prebuild step for the VitePress site.
//
// Generates the site's skill pages from the pack itself, so the docs
// cannot drift from the skills:
//   docs/skills/index.md  — index generated from skills/*/SKILL.md
//                           frontmatter (name, description, version)
//   docs/skills/<name>/   — a copy of each skill's SKILL.md (as
//                           index.md) plus its references/, so the
//                           relative links inside the body keep working
//   docs/router.md        — the router blurb (verbatim) + route table,
//                           taken from skills/using-discord-py-skills
//   website/public/llms.txt — a copy of the repo-root llms.txt
//
// docs/skills/ and docs/public/llms.txt are build artifacts:
// they are gitignored and regenerated by every build. The source of
// truth is always skills/ and llms.txt at the repo root.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SKILLS_DIR = join(ROOT, "skills");
const DOCS = join(ROOT, "docs");
const SKILLS_OUT = join(DOCS, "skills");

// Skills that are new in 0.5.0 get a "new" badge on the index page.
// This is the only hand-maintained list here; everything else is read
// from frontmatter.
const NEW_IN_050 = new Set(["bot-dashboard"]);

function parseFrontmatter(text) {
  const lines = text.split("\n");
  if (lines[0] !== "---") throw new Error("SKILL.md must start with ---");
  const end = lines.indexOf("---", 1);
  if (end === -1) throw new Error("frontmatter is not closed");
  const fm = {};
  let inMetadata = false;
  for (const line of lines.slice(1, end)) {
    if (/^\s/.test(line) && inMetadata) {
      const m = line.trim().match(/^(\w+):\s*"?(.*?)"?$/);
      if (m) fm["metadata." + m[1]] = m[2];
      continue;
    }
    inMetadata = false;
    const m = line.match(/^(\w+):\s*"?(.*?)"?$/);
    if (!m) continue;
    if (m[1] === "metadata") { inMetadata = true; continue; }
    fm[m[1]] = m[2];
  }
  return fm;
}

function firstSentence(desc) {
  // The description's "what it covers" half, before "Use when".
  const idx = desc.indexOf(" Use when");
  const head = idx === -1 ? desc : desc.slice(0, idx);
  return head.trim().replace(/\.$/, "") + ".";
}

// --- skill index -------------------------------------------------------
const skills = [];
for (const name of readdirSync(SKILLS_DIR).sort()) {
  const skillPath = join(SKILLS_DIR, name, "SKILL.md");
  if (!existsSync(skillPath)) continue;
  const fm = parseFrontmatter(readFileSync(skillPath, "utf-8"));
  skills.push({ name, description: fm.description ?? "", version: fm["metadata.version"] ?? "" });
}

rmSync(SKILLS_OUT, { recursive: true, force: true });
mkdirSync(SKILLS_OUT, { recursive: true });

const indexLines = [
  "# Skills",
  "",
  "All twelve skills share the pack version in this release; per-skill",
  "versioning is a post-1.0 change. The table below is generated from",
  "each skill's frontmatter — it is not hand-maintained.",
  "",
  "| Skill | What it covers | Version |",
  "|---|---|---|",
];
for (const s of skills) {
  const badge = NEW_IN_050.has(s.name) ? ' <Badge type="tip" text="new in 0.5.0" />' : "";
  indexLines.push(`| [${s.name}](/skills/${s.name}/)${badge} | ${firstSentence(s.description)} | ${s.version} |`);
}
indexLines.push("");
writeFileSync(join(SKILLS_OUT, "index.md"), indexLines.join("\n"));

// --- per-skill pages ----------------------------------------------------
for (const s of skills) {
  const outDir = join(SKILLS_OUT, s.name);
  mkdirSync(outDir, { recursive: true });
  cpSync(join(SKILLS_DIR, s.name, "SKILL.md"), join(outDir, "index.md"));
  const refs = join(SKILLS_DIR, s.name, "references");
  if (existsSync(refs)) cpSync(refs, join(outDir, "references"), { recursive: true });
}

// --- router page (blurb verbatim + route table) -------------------------
const router = readFileSync(join(SKILLS_DIR, "using-discord-py-skills", "SKILL.md"), "utf-8");
function section(text, heading) {
  const start = text.indexOf("## " + heading);
  if (start === -1) throw new Error("router skill has no section: " + heading);
  const after = text.indexOf("\n## ", start + 1);
  return text.slice(start, after === -1 ? undefined : after).trimEnd();
}
const firstResponse = section(router, "First response");
// The blurb is the blockquote inside "First response".
const blurb = firstResponse.split("\n").filter((l) => l.startsWith(">")).join("\n");
if (!blurb.includes("I'll build this with the discord-py-skills pack")) {
  throw new Error("router blurb not found where expected");
}
const routeTable = section(router, "Route table");
writeFileSync(join(DOCS, "router.md"), [
  "# How the router works",
  "",
  "`using-discord-py-skills` does no bot work itself. It reads the job,",
  "loads the one skill the job needs, and for a new bot it runs them in",
  "this order. On the first bot-work turn it says, verbatim:",
  "",
  blurb,
  "",
  "Load on demand, never preload: the router loads only the skill the",
  "task actually reaches, when it reaches it.",
  "",
  routeTable,
  "",
].join("\n"));

// --- llms.txt ------------------------------------------------------------
// VitePress copies srcDir/public to the output (it ignores an explicit
// publicDir), so llms.txt goes in docs/public/, not website/public/.
mkdirSync(join(DOCS, "public"), { recursive: true });
cpSync(join(ROOT, "llms.txt"), join(DOCS, "public", "llms.txt"));

console.log(`synced ${skills.length} skills, router page, llms.txt`);
